#!/usr/bin/env bash
# shellcheck disable=SC2034,SC2317  # globals read by sourced fns, stubs called indirectly
# install.sh --update (#1920 d): copy before, check after, rollback. A sandbox "server" (agent home,
# lib dir, channel.env, payload stage, units) and a fake installer source; the installer's own steps
# are simulated by editing files the way a re-run does (template line swapped, marker block, new hook,
# new payload). No root, no network, systemctl stubbed. Run: bash tests/test_update_mode.sh
set -euo pipefail

REPO="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
TDIR="$(mktemp -d)"
trap 'rm -rf "${TDIR:?}"' EXIT

PASS=0
FAIL=0
check() {
    local name=$1; shift
    if "$@"; then
        PASS=$((PASS + 1)); printf 'ok   %s\n' "$name"
    else
        FAIL=$((FAIL + 1)); printf 'FAIL %s\n' "$name" >&2
    fi
}

TOKEN_OLD="123456789:AAOLD_token_value_must_never_show_0001"
TOKEN_NEW="123456789:AANEW_token_value_must_never_show_0002"

# make_server <dir> -- an installed «Агент за вечер» in <dir>, the fake installer in <dir>/inst.
make_server() {
    local sb=$1
    local ws="${sb}/home/.claude-lab/jarvis/.claude"
    mkdir -p "${ws}/core/hot" "${ws}/core/warm" "${ws}/azv/soul" "${sb}/home/.claude/projects/-p/memory" \
        "${sb}/lib/hooks" "${sb}/etc/jarvis" "${sb}/stage/soul" "${sb}/systemd" "${sb}/crond" \
        "${sb}/inst/templates" "${sb}/inst/lib" "${sb}/backups" "${sb}/state"
    cp "${REPO}/lib/azv-update.py" "${sb}/inst/lib/azv-update.py"
    printf '# Rules\n\n- Old installer line for {{USER_NAME}}.\n- New installer line.\n{{BRIEF_LINE}}\n' > "${sb}/inst/templates/rules.md"
    printf '# Rules\n\n- Old installer line for Костя.\n- Владелец: отвечай коротко, без списков.\n' > "${ws}/core/rules.md"
    printf '# handoff\n- открыто: позвонить Ивану\n' > "${ws}/core/hot/handoff.md"
    printf '# decisions\n- 18.11 решили X\n' > "${ws}/core/warm/decisions.md"
    printf '{"event":"owner log"}\n' > "${ws}/core/hot/events.jsonl"
    printf '# USER\nИмя: Костя\n' > "${ws}/core/USER.md"
    printf '# Agent\nТы Тест.\n<!-- BEGIN neurootdel-install: team-rules -->\n@old-pointer\n<!-- END neurootdel-install: team-rules -->\n- своя строка владельца в CLAUDE.md\n' > "${ws}/CLAUDE.md"
    printf 'soul v1 line\n' > "${sb}/stage/soul/CLAUDE.md"
    cp "${sb}/stage/soul/CLAUDE.md" "${ws}/azv/soul/CLAUDE.md"
    printf '# MEMORY\n- [заметка](feedback.md)\n<!-- BEGIN neurootdel-install: memory-lessons -->\nold lessons\n<!-- END neurootdel-install: memory-lessons -->\n' \
        > "${sb}/home/.claude/projects/-p/memory/MEMORY.md"
    printf 'владелец не любит длинные ответы\n' > "${sb}/home/.claude/projects/-p/memory/feedback.md"
    printf '{"claudeAiOauth":{"accessToken":"x"}}\n' > "${sb}/home/.claude/.credentials.json"
    printf 'TELEGRAM_BOT_TOKEN=%s\nTELEGRAM_ALLOWED_USER_IDS=111\nCHANNEL_X=1\n' "$TOKEN_OLD" > "${sb}/etc/jarvis/channel.env"
    printf 'print("old hook")\n' > "${sb}/lib/hooks/fact-check-gate.py"
    printf '[Service]\nExecStart=/bin/true\n' > "${sb}/systemd/channel-jarvis.service"
    printf '0 4 * * * agent /lib/agents-reset.sh\n' > "${sb}/crond/agent-agents-reset"
    mkdir -p "${sb}/crontabs"
    printf '# DO NOT EDIT THIS FILE - edit the master and reinstall.\n# (- installed on Thu Nov 19 13:22:45 2026)\n15 9 * * * /bin/true # owner\n' > "${sb}/crontabs/agent"
    printf 'channel-jarvis\n' > "${sb}/active"
}

# Child: sources install.sh, points every path into the sandbox, runs the given commands.
read -r -d '' PRELUDE <<'CHILD' || true
set -euo pipefail
export INSTALL_SH_SOURCED_FOR_TESTING=1
source "$REPO/install.sh"
apply_install_names new
AGENT_USER=agent
AGENT_HOME="$SB/home"; GUARD_LIB_DIR="$SB/lib"; CONFIG_ROOT="$SB/etc"; JARVIS_ENV_DIR="$SB/etc/jarvis"
AZV_STAGE_DIR="$SB/stage"; AZV_AGENT_DIR="$SB/home/.claude-lab/jarvis/.claude/azv"
SUDOERS_FILE="$SB/none"; APT_WRAPPER_BIN="$SB/none"; VERIFY_BIN="$SB/none"; OFFSITE_SETUP_BIN="$SB/none"
UPDATE_RICHARD_DIR="$SB/richard"; INSTALLER_ROOT="$SB/inst"
UPDATE_BACKUP_ROOT="$SB/backups"; UPDATE_LAST_FILE="$SB/state/last-update"; UPDATE_SYSTEMD_DIR="$SB/systemd"
UPDATE_CRON_DIR="$SB/crond"; UPDATE_CRONTAB_DIR="$SB/crontabs"; UPDATE_REQUIRE_ROOT=0
systemctl() {   # remembers which units run: $SB/active (channel-jarvis runs at first)
    printf 'systemctl %s\n' "$*" >> "$SB/systemctl.log"
    case "$1" in
        is-active) grep -qx "$3" "$SB/active" 2>/dev/null ;;
        stop) sed -i "/^$2\$/d" "$SB/active" ;;
        start|restart) grep -qx "$2" "$SB/active" || printf '%s\n' "$2" >> "$SB/active" ;;
        *) return 0 ;;
    esac
}
step() { :; }; log() { printf 'LOG %s\n' "$*"; }
CHILD

run() {   # run <sandbox> <commands...>
    local sb=$1; shift
    SB="$sb" REPO="$REPO" bash -c "${PRELUDE}"$'\n'"$*" 2>&1
}

# simulate_update <sandbox> -- what the --solo re-run does to an installed agent.
simulate_update() {
    local sb=$1 ws="${1}/home/.claude-lab/jarvis/.claude"
    sed -i 's/^- Old installer line for Костя\.$/- New installer line./' "${ws}/core/rules.md"
    python3 - "${ws}/CLAUDE.md" "${sb}/home/.claude/projects/-p/memory/MEMORY.md" <<'PY'
import re, sys
for path, new in ((sys.argv[1], "Справочники (Read по задаче)"), (sys.argv[2], "")):
    s = open(path, encoding="utf-8").read()
    s = re.sub(r"(<!-- BEGIN [^>]*-->\n).*?(<!-- END)", lambda m: m.group(1) + (new + "\n" if new else "") + m.group(2), s, flags=re.S)
    open(path, "w", encoding="utf-8").write(s)
PY
    printf 'soul v2 line\n' > "${sb}/stage/soul/CLAUDE.md"
    cp "${sb}/stage/soul/CLAUDE.md" "${ws}/azv/soul/CLAUDE.md"
    printf 'print("new hook")\n' > "${sb}/lib/hooks/fact-check-gate.py"
    printf 'print("owner gate")\n' > "${sb}/lib/hooks/owner-gate.py"
    mkdir -p "${sb}/home/.claude-lab/shared"
    printf 'new reference\n' > "${sb}/home/.claude-lab/shared/GLOBAL-TEAM-RULES.md"
    sed -i 's|^# (- installed on .*|# (/tmp/tmp.X installed on Thu Nov 19 13:23:53 2026)|' "${sb}/crontabs/agent"   # crontab's own stamp
    grep -q '^CHANNEL_NEW=' "${sb}/etc/jarvis/channel.env" || printf 'CHANNEL_NEW=1\n' >> "${sb}/etc/jarvis/channel.env"
}

# --- 1. arguments ---------------------------------------------------------------------------------
SB1="${TDIR}/s1"; make_server "$SB1"
out=$(run "$SB1" 'parse_args --update; echo "U=$UPDATE_MODE S=$SOLO"')
check "--update sets update mode and --solo" grep -q 'U=1 S=1' <<<"$out"
out=$(run "$SB1" 'update_rollback() { echo "RB:$1"; }; main --update-rollback /x/y')
check "--update-rollback <dir> goes to the rollback, nothing else" grep -qx 'RB:/x/y' <<<"$out"

# --- 2. refusals ----------------------------------------------------------------------------------
out=$(run "$SB1" 'update_prepare' || true)
check "no key: stops with the command to run" grep -q 'NEUROOTDEL_AZV_KEY=<ключ>' <<<"$out"
check "no key: no backup made" test -z "$(ls -A "${SB1}/backups")"
SB2="${TDIR}/s2"; make_server "$SB2"; rm -rf "${SB2}/home/.claude-lab/jarvis/.claude/azv"
out=$(NEUROOTDEL_AZV_KEY=AZV-TEST-0000-0000-0001 run "$SB2" 'update_prepare' || true)
check "not an «Агент за вечер»: stops, points to --solo" grep -q 'только для установленного' <<<"$out"

# --- 3. prepare -> update -> finish: clean ---------------------------------------------------------
export NEUROOTDEL_AZV_KEY=AZV-TEST-0000-0000-0001
out=$(run "$SB1" 'update_prepare')
UDIR=$(cat "${SB1}/state/last-update")
check "prepare: copy and manifest written" test -s "${UDIR}/files.tgz" -a -s "${UDIR}/manifest-before.json"
check "prepare: helper kept next to the copy (rollback without the repo)" test -f "${UDIR}/azv-update.py"
check "prepare: the copy holds the owner's rules" bash -c "tar -tzf '${UDIR}/files.tgz' | grep -qx '${SB1#/}/home/.claude-lab/jarvis/.claude/core/rules.md'"
check "prepare: running agent recorded and stopped" grep -qx 'systemctl stop channel-jarvis' "${SB1}/systemctl.log"
check "prepare: was-active lists only the running unit" test "$(cat "${UDIR}/was-active")" = channel-jarvis
check "prepare: a journal in jsonl is in the copy too" bash -c "tar -tzf '${UDIR}/files.tgz' | grep -q 'core/hot/events.jsonl'"
check "prepare: copy is root-only (0700 dir, 0600 files)" test "$(stat -c %a "$UDIR")" = 700 -a "$(stat -c %a "${UDIR}/files.tgz")" = 600
simulate_update "$SB1"
out=$(run "$SB1" "UPDATE_MODE=1; UPDATE_DIR='$UDIR'; update_check; update_finish")
check "finish: clean update has 0 problems" grep -q 'problems=0' <<<"$out"
check "finish: one result line with the rollback command" grep -q "Обновление готово.*--update-rollback ${UDIR}" <<<"$out"
check "finish: managed hook counted as added" grep -q 'added: .*/lib/hooks/owner-gate.py' "${UDIR}/report.txt"
check "finish: no secret in the report" bash -c "! grep -qF -e '$TOKEN_OLD' -e '$TOKEN_NEW' '${UDIR}/report.txt'"
check "finish: the agent that ran before runs again" grep -qx channel-jarvis "${SB1}/active"
check "finish: owner line in rules.md still there" grep -q 'Владелец: отвечай коротко' "${SB1}/home/.claude-lab/jarvis/.claude/core/rules.md"

# --- 4. idempotent: the same update again changes nothing -----------------------------------------
out=$(run "$SB1" 'update_prepare'); UDIR2=$(cat "${SB1}/state/last-update")
simulate_update "$SB1"
out=$(run "$SB1" "UPDATE_MODE=1; UPDATE_DIR='$UDIR2'; update_check; update_finish")
check "second run: changed=0 added=0 problems=0" grep -q 'changed=0 added=0 removed=0 problems=0' <<<"$out"
check "second run: its own copy dir" test "$UDIR2" != "$UDIR"

# --- 5. problems: owner text lost, journal changed, bot token changed ------------------------------
SB3="${TDIR}/s3"; make_server "$SB3"
run "$SB3" 'update_prepare' >/dev/null; UDIR3=$(cat "${SB3}/state/last-update")
ws3="${SB3}/home/.claude-lab/jarvis/.claude"
sed -i '/Владелец: отвечай коротко/d' "${ws3}/core/rules.md"
printf -- '- новое\n' >> "${ws3}/core/hot/handoff.md"
sed -i "s|^TELEGRAM_BOT_TOKEN=.*|TELEGRAM_BOT_TOKEN=${TOKEN_NEW}|" "${SB3}/etc/jarvis/channel.env"
printf 'owner edited soul\n' > "${ws3}/azv/soul/CLAUDE.md.tmp"
out=$(run "$SB3" "UPDATE_MODE=1; UPDATE_DIR='$UDIR3'; update_check; update_finish" || true)
check "problem: finish says the owner's files were touched" grep -q 'задело файлы владельца' <<<"$out"
check "problem: lost owner line named by line number (placeholder-only template line does not hide it)" \
    grep -q 'OWNER_TEXT .*core/rules.md: line 4 of the copy' "${UDIR3}/report.txt"
check "problem: the report never quotes the owner's text" bash -c "! grep -q 'отвечай коротко' '${UDIR3}/report.txt'"
check "problem: journal change is STRICT" grep -q 'STRICT changed: .*core/hot/handoff.md' "${UDIR3}/report.txt"
check "problem: bot token change named by key only" grep -q 'ENV .*channel.env: TELEGRAM_BOT_TOKEN changed' "${UDIR3}/report.txt"
check "problem: token value never in the report" bash -c "! grep -qF -e '$TOKEN_OLD' -e '$TOKEN_NEW' '${UDIR3}/report.txt'"

# --- 5b. owner's own marker block, a file turned into a link, the copy checked against the manifest --
SB6="${TDIR}/s6"; make_server "$SB6"
ws6="${SB6}/home/.claude-lab/jarvis/.claude"
printf '<!-- notes:begin -->\nмой собственный блок заметок\n<!-- notes:end -->\n' >> "${ws6}/CLAUDE.md"
printf 'owner file\n' > "${ws6}/core/own.md"
run "$SB6" 'update_prepare' >/dev/null; UDIR6=$(cat "${SB6}/state/last-update")
python3 - "${ws6}/CLAUDE.md" <<'PY'
import re, sys
s = open(sys.argv[1], encoding="utf-8").read()
open(sys.argv[1], "w", encoding="utf-8").write(re.sub(r"<!-- notes:begin -->.*?<!-- notes:end -->\n", "", s, flags=re.S))
PY
rm "${ws6}/core/own.md"; ln -s /etc/hostname "${ws6}/core/own.md"
out=$(run "$SB6" "UPDATE_MODE=1; UPDATE_DIR='$UDIR6'; update_check; update_finish" || true)
check "owner's own block (not an installer tag) removed = OWNER_TEXT" grep -q 'OWNER_TEXT .*/CLAUDE.md: line' "${UDIR6}/report.txt"
check "a file that became a symlink = TYPE problem, never read through" grep -q 'TYPE .*core/own.md: F -> L' "${UDIR6}/report.txt"
python3 - "${UDIR6}/manifest-before.json" <<'PY'
import json, sys
m = json.load(open(sys.argv[1])); k = next(p for p, v in m.items() if p.endswith("core/rules.md")); m[k][1] = "0" * 64
json.dump(m, open(sys.argv[1] + ".bad", "w"))
PY
check "verify: a copy that differs from the manifest fails" bash -c "! python3 '${UDIR6}/azv-update.py' verify '${UDIR6}/manifest-before.json.bad' '${UDIR6}/files.tgz' >/dev/null"
check "verify: the real copy passes" bash -c "python3 '${UDIR6}/azv-update.py' verify '${UDIR6}/manifest-before.json' '${UDIR6}/files.tgz' >/dev/null"

# --- 6. owner's own edit of a payload file: replaced, reported, kept in the copy --------------------
SB4="${TDIR}/s4"; make_server "$SB4"
printf 'soul v1 line\nмоя правка души\n' > "${SB4}/home/.claude-lab/jarvis/.claude/azv/soul/CLAUDE.md"
run "$SB4" 'update_prepare' >/dev/null; UDIR4=$(cat "${SB4}/state/last-update")
simulate_update "$SB4"
out=$(run "$SB4" "UPDATE_MODE=1; UPDATE_DIR='$UDIR4'; update_check; update_finish")
check "soul edit: reported, not a failure" grep -q 'problems=0 soul_edits=1' <<<"$out"
check "soul edit: named in the report" grep -q 'SOUL_EDIT .*azv/soul/CLAUDE.md' "${UDIR4}/report.txt"

# --- 7. rollback: only the update's work goes back ------------------------------------------------
ws1="${SB1}/home/.claude-lab/jarvis/.claude"
printf -- '- записано после обновления\n' >> "${ws1}/core/hot/handoff.md"      # agent wrote after the update
printf 'owner changed the new reference\n' > "${SB1}/home/.claude-lab/shared/GLOBAL-TEAM-RULES.md"
printf 'print("owner patched the new hook")\n' > "${SB1}/lib/hooks/fact-check-gate.py"   # changed again after the update
sed -i "s|^TELEGRAM_BOT_TOKEN=.*|TELEGRAM_BOT_TOKEN=${TOKEN_NEW}|" "${SB1}/etc/jarvis/channel.env"   # owner's new bot after the update
: > "${SB1}/systemctl.log"; printf 'channel-jarvis\n' > "${SB1}/active"
out=$(run "$SB1" "update_rollback '$UDIR'")
check "rollback: done line" grep -q 'Откат готов' <<<"$out"
check "rollback: rules.md back to the old installer line" grep -q 'Old installer line for Костя' "${ws1}/core/rules.md"
check "rollback: payload back to v1" grep -qx 'soul v1 line' "${ws1}/azv/soul/CLAUDE.md"
check "rollback: stage back to v1 (next update compares right)" grep -qx 'soul v1 line' "${SB1}/stage/soul/CLAUDE.md"
check "rollback: added hook removed" test ! -e "${SB1}/lib/hooks/owner-gate.py"
check "rollback: file changed again after the update keeps the newer copy" grep -q 'owner patched' "${SB1}/lib/hooks/fact-check-gate.py"
check "rollback: conflict named in the rollback list" bash -c "grep -q 'conflict_kept_newer .*fact-check-gate.py' '${UDIR}'/rollback-*.txt"
check "rollback: added file the owner changed since is kept" grep -q 'owner changed' "${SB1}/home/.claude-lab/shared/GLOBAL-TEAM-RULES.md"
check "rollback: journal written after the update is kept" grep -q 'записано после обновления' "${ws1}/core/hot/handoff.md"
check "rollback: the owner's newer bot token is not reverted" grep -qF "TELEGRAM_BOT_TOKEN=${TOKEN_NEW}" "${SB1}/etc/jarvis/channel.env"
check "rollback: CLAUDE.md marker block back" grep -qx '@old-pointer' "${ws1}/CLAUDE.md"
check "rollback: the agent that ran is started" grep -qx 'systemctl start channel-jarvis' "${SB1}/systemctl.log"
check "rollback: current copies saved first" bash -c "ls '${UDIR}'/rolled-back-*.tgz >/dev/null"
out=$(run "$SB1" "update_rollback '${TDIR}/nope'" || true)
check "rollback: unknown dir stops with a message" grep -q 'Копия обновления не найдена' <<<"$out"
mkdir -p "${TDIR}/elsewhere/update-x"; cp "${UDIR}/files.tgz" "${UDIR}/azv-update.py" "${TDIR}/elsewhere/update-x/"
out=$(run "$SB1" "update_rollback '${TDIR}/elsewhere/update-x'" || true)
check "rollback: a copy outside the backup root is refused (helper runs as root)" grep -q 'только из копии' <<<"$out"

# --- 7b. a removed directory comes back with its mode; no after record = nothing touched -------------
SB7="${TDIR}/s7"; make_server "$SB7"
mkdir -m 0750 "${SB7}/home/.claude-lab/jarvis/.claude/core/notes"; printf 'n\n' > "${SB7}/home/.claude-lab/jarvis/.claude/core/notes/a.md"
run "$SB7" 'update_prepare' >/dev/null; UDIR7=$(cat "${SB7}/state/last-update")
rm -rf "${SB7}/home/.claude-lab/jarvis/.claude/core/notes"
run "$SB7" "UPDATE_MODE=1; UPDATE_DIR='$UDIR7'; update_check" >/dev/null || true
run "$SB7" "update_rollback '$UDIR7'" >/dev/null
check "rollback: removed dir back with its mode 750" test "$(stat -c %a "${SB7}/home/.claude-lab/jarvis/.claude/core/notes" 2>/dev/null)" = 750
check "rollback: and its file back" test -f "${SB7}/home/.claude-lab/jarvis/.claude/core/notes/a.md"
SB8="${TDIR}/s8"; make_server "$SB8"
run "$SB8" 'update_prepare' >/dev/null; UDIR8=$(cat "${SB8}/state/last-update")
printf 'x\n' > "${SB8}/lib/hooks/owner-gate.py"
out=$(run "$SB8" "update_rollback '$UDIR8'" || true)
check "rollback without an after record: refuses" grep -q 'Откат не прошёл' <<<"$out"
check "rollback without an after record: nothing removed" test -f "${SB8}/lib/hooks/owner-gate.py"
check "rollback without an after record: the agent is started again" grep -qx channel-jarvis "${SB8}/active"

# --- 7c. one update at a time ---------------------------------------------------------------------
SB9="${TDIR}/s9"; make_server "$SB9"
( exec 9>"${SB9}/state/update.lock"; flock 9; sleep 5 ) & LOCKER=$!
sleep 0.5
out=$(run "$SB9" 'update_prepare' || true)
kill "$LOCKER" 2>/dev/null || true; wait "$LOCKER" 2>/dev/null || true
check "lock: a second update while one runs stops" grep -q 'уже идёт' <<<"$out"
check "lock: and makes no copy" test -z "$(ls -A "${SB9}/backups")"

# --- 8. an update stopped half way says how to roll back and starts the agent ----------------------
: > "${SB1}/systemctl.log"; : > "${SB1}/active"
out=$(run "$SB1" "UPDATE_MODE=1; UPDATE_DIR='$UDIR'; UPDATE_DONE=0; _update_abort")
check "abort: rollback command printed" grep -q "Обновление не закончилось. Откат: .*--update-rollback ${UDIR}" <<<"$out"
check "abort: agent started again" grep -qx 'systemctl start channel-jarvis' "${SB1}/systemctl.log"
SB5="${TDIR}/s5"; make_server "$SB5"
run "$SB5" 'update_prepare' >/dev/null; UDIR5=$(cat "${SB5}/state/last-update")
printf 'print("owner gate")\n' > "${SB5}/lib/hooks/owner-gate.py"   # half an update
: > "${SB5}/systemctl.log"
run "$SB5" "UPDATE_MODE=1; UPDATE_DIR='$UDIR5'; UPDATE_DONE=0; _update_abort" >/dev/null 2>&1
check "abort: what the half update left is recorded before the agent starts" grep -q 'owner-gate.py' "${UDIR5}/changes.json"
mkdir -p "${SB5}/home/.claude-lab/jarvis/.claude/core/hot"; printf 'agent wrote after abort\n' > "${SB5}/home/.claude-lab/jarvis/.claude/core/hot/new-note.md"
run "$SB5" "update_rollback '$UDIR5'" >/dev/null
check "abort+rollback: the half update's file removed" test ! -e "${SB5}/lib/hooks/owner-gate.py"
check "abort+rollback: a note the agent wrote after the abort stays" test -f "${SB5}/home/.claude-lab/jarvis/.claude/core/hot/new-note.md"
out=$(run "$SB1" "UPDATE_MODE=1; UPDATE_DIR='$UDIR'; UPDATE_DONE=1; _update_abort; echo QUIET")
check "abort: silent after a finished update" test "$out" = QUIET

printf '\n%d passed, %d failed\n' "$PASS" "$FAIL"
[[ "$FAIL" -eq 0 ]]
